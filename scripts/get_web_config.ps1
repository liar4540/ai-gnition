# Write the web dashboard's server config (frontend\server\.env, git-ignored).
# The API server reads the Orchestrate URL/key and Google values from the root .env itself;
# this only adds the agent id it should talk to.
# Needs nyp_inbox_agent deployed (scripts\deploy.ps1 -Live).
# Usage:  powershell -ExecutionPolicy Bypass -File scripts\get_web_config.ps1
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

$serverUrl, $apiKey = $null, $null
foreach ($line in Get-Content ".env") {
    if ($line -match '^\s*WXO_SERVER_URL\s*=\s*"?(.*?)"?\s*$') { $serverUrl = $Matches[1] }
    if ($line -match '^\s*WXO_API_KEY\s*=\s*"?(.*?)"?\s*$') { $apiKey = $Matches[1] }
}
. (Join-Path $PSScriptRoot "_orch.ps1")
Connect-Orch $serverUrl $apiKey

$ErrorActionPreference = "Continue"
$env:COLUMNS = "1000"
$list = (& $script:OrchExe agents list -v 2>&1 | ForEach-Object { "$_" }) -join "`n"
$ErrorActionPreference = "Stop"
if ($list -notmatch '"id":\s*"([0-9a-f-]{36})",\s*"name":\s*"nyp_inbox_agent"') {
    throw "nyp_inbox_agent was not found. Run scripts\deploy.ps1 -Live first."
}
$agentId = $Matches[1]

$serverEnv = Join-Path $Root "frontend\server\.env"
$lines = @(
    "# Generated by scripts\get_web_config.ps1. Git-ignored.",
    "WXO_AGENT_ID=$agentId",
    "API_PORT=8787"
)
[IO.File]::WriteAllLines($serverEnv, $lines)
Write-Host "Wrote $serverEnv (WXO_AGENT_ID=$agentId). Next: cd frontend; npm run dev"
