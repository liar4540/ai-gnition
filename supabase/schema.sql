-- Trustworthy Inbox Agent: database tables for Supabase (Postgres).
-- Run once in Supabase: SQL Editor -> New query -> paste this file -> Run.
-- Safe to run again (IF NOT EXISTS).
--
-- Same tables and rules as the SQLite schema in tools/nyp_store.py. No email subject, body or
-- sender is ever stored; draft text is deleted after the decision, leaving only its hash.
--
-- Security: row level security is ON with no policies, so the public "anon" key can read and
-- write nothing. Only the secret (service role) key, kept in the Orchestrate connection nyp_db
-- and in the dashboard server's environment, can use these tables.

create table if not exists sync_state (
  id integer primary key check (id = 1),
  history_id text,
  last_run text
);

create table if not exists analyses (
  message_id text primary key,
  thread_id text,
  category text check (category in ('routine', 'important', 'suspicious')),
  risk text check (risk in ('low', 'medium', 'high')),
  confidence integer,
  band text,
  evidence text,                       -- JSON list of evidence codes
  quarantined integer not null default 0,
  created_at text
);

create table if not exists tasks (
  task_id bigint generated by default as identity primary key,
  thread_id text,
  source_message_ids text,
  title text,
  deadline text,
  status text check (status in ('open', 'pending_approval', 'on_hold', 'done', 'cancelled')),
  confidence integer,
  reason text,
  delta text,
  calendar_event_id text,
  created_at text,
  updated_at text
);

create table if not exists drafts (
  draft_id bigint generated by default as identity primary key,
  task_id bigint,
  action text,
  content text,                        -- exact action payload as canonical JSON; NULL after the decision
  content_hash text,
  deleted integer not null default 0
);

create table if not exists approvals (
  approval_id text primary key,
  task_id bigint,
  action text check (action in ('send_reply', 'calendar_create', 'calendar_move')),
  content_hash text,
  decision text check (decision in ('pending', 'approved', 'rejected', 'cancelled', 'expired')),
  state text check (state in ('prepared', 'approved', 'attempted', 'confirmed', 'failed')),
  expires_at text,
  used integer not null default 0,
  decided_at text,
  result_id text,
  telegram_message_id text
);

create table if not exists activity_log (
  id bigint generated by default as identity primary key,
  ts text,
  actor text,
  event text,
  result text
);

-- The owner's Send / Don't send / Edit from the web dashboard. Written only by the dashboard
-- server after the owner signs in; applied by the agent's nyp_check_approvals with the same
-- checks as a Telegram press.
create table if not exists web_decisions (
  id bigint generated by default as identity primary key,
  approval_id text,
  decision text check (decision in ('approve', 'reject', 'edit')),
  body text,                           -- edited reply text; NULL once applied
  status text not null default 'queued' check (status in ('queued', 'applied', 'failed')),
  result text,
  created_at text,
  applied_at text
);

create index if not exists tasks_thread_idx on tasks (thread_id);
create index if not exists drafts_task_idx on drafts (task_id, action);
create index if not exists approvals_decision_idx on approvals (decision);
create index if not exists web_decisions_status_idx on web_decisions (status);

alter table sync_state enable row level security;
alter table analyses enable row level security;
alter table tasks enable row level security;
alter table drafts enable row level security;
alter table approvals enable row level security;
alter table activity_log enable row level security;
alter table web_decisions enable row level security;
